CREATE TABLE IF NOT EXISTS hotels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    address VARCHAR(255) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_hotels_name ON hotels (name);

CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL,
    number VARCHAR(20) NOT NULL,
    available BOOLEAN NOT NULL,
    times_booked INT NOT NULL,
    CONSTRAINT fk_rooms_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id),
    CONSTRAINT uk_rooms_hotel_number UNIQUE (hotel_id, number)
);

CREATE INDEX IF NOT EXISTS idx_rooms_available_times ON rooms (available, times_booked, id);

CREATE TABLE IF NOT EXISTS room_locks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    request_id VARCHAR(80) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    released BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_room_locks_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT uk_room_locks_request UNIQUE (request_id)
);

CREATE INDEX IF NOT EXISTS idx_room_locks_room_dates ON room_locks (room_id, start_date, end_date);
